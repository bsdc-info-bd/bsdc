/**
 * The bindings this worker runs with.
 *
 * Everything here is a secret or a documented var, set with `wrangler secret
 * put` or in `wrangler.toml`. Nothing is compiled in, which is the point: a
 * VAPID private key in a repository is a key that signs pushes for anybody who
 * reads the repository.
 */
export interface Env {
  /** Supabase project URL, e.g. https://xxxx.supabase.co. */
  SUPABASE_URL: string;
  /**
   * The publishable/anon key. This worker never holds the service key — it does
   * not need one: every function it calls is secret-gated in the database, and
   * the secret is the authorisation.
   */
  SUPABASE_ANON_KEY: string;
  /**
   * The same string stored in `bsdc.push_settings` as `flush_secret`. It is what
   * lets this worker read members' pending notifications and mark them sent.
   */
  PUSH_FLUSH_SECRET: string;
  /** PKCS#8 DER of the P-256 signing key, base64url. Generated by `npm run push:keys`. */
  PUSH_VAPID_PRIVATE_KEY: string;
  /** The uncompressed public point, base64url: the `k=` half of every request. */
  PUSH_VAPID_PUBLIC_KEY: string;
  /** The `sub` claim: a contact address the push services can complain to. */
  PUSH_VAPID_SUBJECT?: string;
  /** Optional comma-separated allowlist of origins for the HTTP endpoint. */
  ADMIN_ORIGINS?: string;
  /** Set to `1` to include timing detail in the response body. */
  VERBOSE?: string;
}

/** The subject, normalised to the `mailto:` form the specification requires. */
export function vapidSubject(raw: string | undefined): string {
  const trimmed = (raw ?? '').trim();
  const address = trimmed.length > 0 ? trimmed : 'admin@bsdc.info.bd';
  return address.startsWith('mailto:') ? address : `mailto:${address}`;
}

/** The list of origins the HTTP trigger will answer to. */
export function adminOrigins(raw: string | undefined): string[] {
  return (raw ?? '')
    .split(',')
    .map((origin) => origin.trim().replace(/\/+$/, ''))
    .filter((origin) => origin.length > 0);
}

/**
 * The route list, read from the thing that gets built.
 *
 * §8.5 asks for coverage "generated from the prerender manifest rather than
 * typed". Copying `main-site/src/lib/seo/static-routes.json` into the console by
 * hand is exactly the drift it is warning about: the day someone adds a route,
 * the console would keep reporting the old sixteen and the coverage screen would
 * be confidently wrong.
 *
 * So this is a build step, not a paste. It reads the manifest the prerenderer
 * itself reads, adds the routes that manifest cannot know about (the ones
 * generated from the database — a post, a product, a vendor), and writes a
 * TypeScript module the console imports. `npm run routes` regenerates it;
 * `npm run routes:check` fails when it is out of date, which is what the test
 * suite runs so a stale copy cannot be committed.
 *
 * Run: node scripts/sync-routes.mjs [--check]
 */

import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const manifestPath = resolve(here, '../../main-site/src/lib/seo/static-routes.json');
const outPath = resolve(here, '../src/routes.generated.ts');

/**
 * Routes that exist because of a database row, so no static manifest can list
 * them. Each pattern is what the path looks like, not a list of real paths, and
 * the console matches these but never counts them towards coverage — a route
 * family with ten thousand members cannot be "covered by an override".
 */
const DYNAMIC_ROUTES = [
  { pattern: '/:postSlug', label: 'A post', source: 'public.posts' },
  { pattern: '/products/:slug', label: 'A product', source: 'public.products' },
  { pattern: '/courses/:slug', label: 'A course', source: 'public.courses' },
  { pattern: '/v/:slug', label: 'A vendor page', source: 'public.mk_vendors' },
  { pattern: '/groups/:slug', label: 'A group', source: 'public.groups' },
];

function normalisePath(raw) {
  const withoutQuery = (raw ?? '').split('#')[0]?.split('?')[0] ?? '';
  const trimmed = withoutQuery.replace(/\s+/g, '').toLowerCase();
  const collapsed = `/${trimmed}`.replace(/\/{2,}/g, '/');
  const stripped = collapsed.length > 1 ? collapsed.replace(/\/+$/, '') : collapsed;
  return stripped === '' ? '/' : stripped;
}

const raw = JSON.parse(await readFile(manifestPath, 'utf8'));
if (!Array.isArray(raw.routes) || raw.routes.length === 0) {
  throw new Error(`${manifestPath} has no routes array; the prerenderer would build nothing.`);
}

const staticRoutes = raw.routes
  .map((route) => ({
    path: normalisePath(route.path),
    title: (route.title ?? '').trim(),
    description: (route.description ?? '').trim(),
    component: route.component ?? '',
  }))
  .sort((a, b) => a.path.localeCompare(b.path));

// Two routes with one path means the prerenderer writes the second over the
// first and the site silently loses a page. Better to fail the build.
const seen = new Map();
for (const route of staticRoutes) {
  const prior = seen.get(route.path);
  if (prior) {
    throw new Error(
      `${manifestPath} lists ${route.path} twice (${prior} and ${route.component}). The prerenderer would write one over the other.`,
    );
  }
  seen.set(route.path, route.component);
}

const header = `/**
 * GENERATED by admin-site/scripts/sync-routes.mjs — do not edit.
 *
 * Source: main-site/src/lib/seo/static-routes.json (the file the prerenderer
 * reads) plus the dynamic route families that no static file can list.
 * Regenerate with \`npm run routes\` in admin-site; \`npm run routes:check\` fails
 * the test suite when this file and the manifest disagree.
 */
`;

const body = `${header}
export interface StaticRoute {
  readonly path: string;
  readonly title: string;
  readonly description: string;
  readonly component: string;
}

export interface DynamicRoute {
  readonly pattern: string;
  readonly label: string;
  readonly source: string;
}

/** The ${staticRoutes.length} routes the prerenderer writes as real HTML. */
export const STATIC_ROUTES: readonly StaticRoute[] = ${JSON.stringify(staticRoutes, null, 2)};

/** Route families that exist per database row, matched but never counted. */
export const DYNAMIC_ROUTES: readonly DynamicRoute[] = ${JSON.stringify(DYNAMIC_ROUTES, null, 2)};

/** The manifest this file was generated from, for the audit trail. */
export const ROUTES_SOURCE = 'main-site/src/lib/seo/static-routes.json';
`;

const check = process.argv.includes('--check');
if (check) {
  const current = await readFile(outPath, 'utf8').catch(() => '');
  if (current !== body) {
    console.error(
      'admin-site/src/routes.generated.ts is out of date with the prerender manifest.\nRun `npm run routes` in admin-site and commit the result.',
    );
    process.exit(1);
  }
  console.log(`routes.generated.ts is current (${staticRoutes.length} static routes).`);
} else {
  await writeFile(outPath, body, 'utf8');
  console.log(`Wrote ${outPath} (${staticRoutes.length} static routes, ${DYNAMIC_ROUTES.length} dynamic families).`);
}

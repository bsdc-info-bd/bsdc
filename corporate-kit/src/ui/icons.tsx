export function PortalIcon({
  icon,
  size = 16,
}: {
  readonly icon: PortalIconKey;
  readonly size?: number | undefined;
}): ReactElement {
  switch (icon) {
    case 'command':
      return <CommandIcon size={size} />;
    case 'shield':
      return <ShieldIcon size={size} />;
    case 'award':
      return <AwardIcon size={size} />;
    case 'megaphone':
      return <MegaphoneIcon size={size} />;
    case 'users':
    case 'directory':
      return <UsersIcon size={size} />;
    case 'sliders':
      return <SlidersIcon size={size} />;
    case 'layers':
      return <LayersIcon size={size} />;
    case 'network':
      return <NetworkIcon size={size} />;
    case 'activity':
    case 'status':
      return <ActivityIcon size={size} />;
    case 'chat':
      return <ChatIcon size={size} />;
    case 'verify':
      return <CheckCircleIcon size={size} />;
    default:
      return <GlobeIcon size={size} />;
  }
}

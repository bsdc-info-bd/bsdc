import { CheckCircle2, CircleAlert, CircleX, Copy, Loader2, MinusCircle, Play } from 'lucide-react';
import { useCallback, useEffect, useState } from 'react';
import { useTranslation } from 'react-i18next';
import { toast } from 'sonner';

import { Button, Card, PageSkeleton, SectionHeading } from '@/design-system';
import { HealthCheckCard } from '@/components/diagnostics/HealthCheckCard';
import { Seo } from '@/components/seo/Seo';
import {
  checksReport,
  runChecks,
  summariseChecks,
  type CheckResult,
  type CheckState,
} from '@/lib/diagnostics/checks';
import { buildId, liveProbes } from '@/lib/diagnostics/live-probes';

/**
 * The page that answers "is the platform working" with evidence.
 *
 * It exists because every previous answer to that question was an argument. A
 * member says pictures do not load; a developer says the build is green; both
 * are describing different things and neither can see the other's. This page
 * runs the checks that separate them — configuration, the site's own API, both
 * picture hosts, the database functions, the live socket, the browser's own
 * limits — and prints a sentence for each, plus a report the member can copy.
 *
 * Nothing on it is secret: no token, no endpoint, no personal data. The report
 * is generated by `checksReport`, which is tested to contain none of those.
 */
export default function SystemCheckPage() {
  const { t, i18n } = useTranslation();
  const [checks, setChecks] = useState<CheckResult[] | null>(null);
  const [running, setRunning] = useState(false);

  const run = useCallback(async () => {
    setRunning(true);
    try {
      setChecks(await runChecks(liveProbes()));
    } catch {
      toast.error(t('diagnostics.failed'));
    } finally {
      setRunning(false);
    }
  }, [t]);

  useEffect(() => {
    void run();
  }, [run]);

  async function copyReport() {
    if (checks === null) return;
    const report = checksReport(checks, {
      build: buildId(),
      language: i18n.language,
      userAgent: navigator.userAgent,
    });
    try {
      await navigator.clipboard.writeText(report);
      toast.success(t('diagnostics.copied'));
    } catch {
      // Clipboard access is refused in some browsers without a gesture on a
      // secure context; the text is in the page either way.
      toast.error(t('diagnostics.copyFailed'));
    }
  }

  const summary = checks === null ? null : summariseChecks(checks);

  return (
    <div className="mx-auto w-full max-w-3xl px-3 py-6">
      <Seo
        title={t('diagnostics.title')}
        description={t('diagnostics.description')}
        path="/system-check"
        noindex
      />
      <SectionHeading title={t('diagnostics.title')} description={t('diagnostics.description')} />

      <div className="mt-4 flex flex-wrap items-center gap-2">
        <Button
          onClick={() => void run()}
          disabled={running}
          iconStart={
            running ? (
              <Loader2 aria-hidden className="size-4 animate-spin" />
            ) : (
              <Play aria-hidden className="size-4" />
            )
          }
        >
          {running ? t('diagnostics.running') : t('diagnostics.runAgain')}
        </Button>
        <Button
          variant="secondary"
          onClick={() => void copyReport()}
          disabled={checks === null}
          iconStart={<Copy aria-hidden className="size-4" />}
        >
          {t('diagnostics.copy')}
        </Button>
      </div>

      {summary !== null ? (
        <p role="status" className="mt-4 rounded-xl bg-surface-2 px-3 py-2 text-sm">
          {t(`diagnostics.verdict.${summary.state}`, {
            failed: summary.failed,
            warned: summary.warned,
            total: summary.total,
          })}
        </p>
      ) : null}

      <div className="mt-4 grid gap-3">
        {checks === null ? (
          <PageSkeleton label={t('diagnostics.running')} />
        ) : (
          checks.map((check) => (
            <div key={check.id}>
              <HealthCheckCard check={check} />
            </div>
          ))
        )}
      </div>

      <Card className="mt-4 p-4">
        <p className="text-xs text-muted">{t('diagnostics.privacy')}</p>
      </Card>
    </div>
  );
}

/** The icon for a state, exported so the card and any future summary agree. */
export function StateIcon({ state }: { state: CheckState }) {
  if (state === 'ok') return <CheckCircle2 aria-hidden className="size-4 text-green-700" />;
  if (state === 'warn') return <CircleAlert aria-hidden className="size-4 text-warn" />;
  if (state === 'fail') return <CircleX aria-hidden className="size-4 text-danger" />;
  return <MinusCircle aria-hidden className="size-4 text-muted" />;
}
